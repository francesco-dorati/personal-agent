#!/usr/bin/env python3
"""Personal Agent setup.

Asks a few questions, saves the answers in `.env`, and writes `AGENT.local.md`:
the agent guide with your settings filled in, as one file you can give to any
assistant. Safe to re-run: current values are offered as defaults.

    python3 setup.py            # interactive
    python3 setup.py --render   # only rebuild AGENT.local.md from .env
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ENV = ROOT / ".env"
GUIDE = ROOT / "AGENT.md"
LOCAL = ROOT / "AGENT.local.md"

# Settings asked by setup, in order. (key, question, default)
QUESTIONS = [
    ("USER_NAME", "Your name", ""),
    ("NOTION_ROOT_PAGE_ID", "Link or ID of your Notion root page", ""),
    ("USER_LANGUAGE", "Language for entries written in Notion", "English"),
    ("USER_TIMEZONE", "Your time zone (IANA, e.g. Europe/Rome)", "UTC"),
    ("NOTION_TOKEN", "Notion integration token (optional, Enter to skip)", ""),
]
# Settings that may appear in AGENT.local.md. Secrets never do.
PUBLIC_KEYS = ["USER_NAME", "NOTION_ROOT_PAGE_ID", "USER_LANGUAGE", "USER_TIMEZONE"]


def read_env() -> dict[str, str]:
    values: dict[str, str] = {}
    if ENV.exists():
        for line in ENV.read_text().splitlines():
            m = re.match(r"\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$", line)
            if m:
                values[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    return values


def write_env(values: dict[str, str]) -> None:
    """Update keys in place, keeping comments and unknown keys."""
    lines = ENV.read_text().splitlines() if ENV.exists() else [
        "# Personal Agent settings. Written by setup.py. Never commit this file."
    ]
    seen = set()
    for i, line in enumerate(lines):
        m = re.match(r"\s*([A-Z_][A-Z0-9_]*)\s*=", line)
        if m and m.group(1) in values:
            lines[i] = f"{m.group(1)}={values[m.group(1)]}"
            seen.add(m.group(1))
    lines += [f"{k}={v}" for k, v in values.items() if k not in seen]
    ENV.write_text("\n".join(lines) + "\n")


def parse_page_id(text: str) -> str:
    """Accept a Notion URL or ID; return the 32-hex ID, or '' if none."""
    found = re.findall(r"[0-9a-fA-F]{32}", text.replace("-", ""))
    return found[-1].lower() if found else ""


def secret_display(key: str, value: str) -> str:
    if key == "NOTION_TOKEN" and value:
        return value[:6] + "…"
    return value


def ask(values: dict[str, str]) -> dict[str, str]:
    print("Personal Agent setup. Press Enter to keep the value in [brackets].\n")
    for key, question, default in QUESTIONS:
        current = values.get(key) or default
        shown = secret_display(key, current)
        while True:
            answer = input(f"{question} [{shown}]: ").strip()
            value = answer or current
            if key == "NOTION_ROOT_PAGE_ID":
                pid = parse_page_id(value)
                if not pid:
                    print("  Paste the page link or its 32-character ID.")
                    continue
                value = pid
            if key == "USER_NAME" and not value:
                print("  A name is needed.")
                continue
            values[key] = value
            break
    return values


def render(values: dict[str, str]) -> None:
    rows = "\n".join(
        f"- `{k}` = `{values.get(k, '')}`" for k in PUBLIC_KEYS if values.get(k)
    )
    header = f"""<!-- Generated by setup.py from AGENT.md and .env. Do not edit: re-run setup. -->

## 0. This installation

These settings override the defaults described in the rest of this guide.

{rows}

The user is **{values.get('USER_NAME', 'the user')}**. Write entries in
{values.get('USER_LANGUAGE', 'English')}, and read and write dates in the
{values.get('USER_TIMEZONE', 'UTC')} time zone.

---

"""
    guide = GUIDE.read_text()
    # Insert after the intro (before the first "## " section).
    cut = guide.index("\n## ")
    LOCAL.write_text(guide[:cut] + "\n\n" + header + guide[cut + 1:])
    print(f"\nWrote {LOCAL.name}: give this single file to your assistant.")


def main() -> None:
    values = read_env()
    if "--render" not in sys.argv:
        values = ask(values)
        write_env(values)
        print(f"\nSaved settings to {ENV.name}.")
    missing = [k for k in ("USER_NAME", "NOTION_ROOT_PAGE_ID") if not values.get(k)]
    if missing:
        sys.exit(f"Missing {', '.join(missing)}: run `python3 setup.py` first.")
    render(values)


if __name__ == "__main__":
    main()
